export function getLocationBySlug(slug: string): FishingLocation | undefined {
    return fishingLocations.find(l => l.slug === slug);
}

export function getAllLocations(): FishingLocation[] {
    return fishingLocations;
}

export function getLocationsByCounty(county: string): FishingLocation[] {
    return fishingLocations.filter(l => l.county === county);
}

export function getAllCounties(): string[] {
    return [...new Set(fishingLocations.map(l => l.county))];
}

export function countyToSlug(county: string): string {
    return county
        .toLowerCase()
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '')
        .replace(/ş|ș/g, 's')
        .replace(/ţ|ț/g, 't')
        .replace(/ă|â/g, 'a')
        .replace(/î/g, 'i')
        .replace(/\s+/g, '-')
        .replace(/[^a-z0-9-]/g, '');
}

export function getCountyBySlug(slug: string): string | undefined {
    return getAllCounties().find(c => countyToSlug(c) === slug);
}

export function getAllCountySlugs(): { slug: string; name: string }[] {
    return getAllCounties()
        .map(c => ({ slug: countyToSlug(c), name: c }))
        .sort((a, b) => a.name.localeCompare(b.name, 'ro'));
}
